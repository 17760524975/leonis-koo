/* 十二生肖关卡造型
 * ---------------------------------------------------------------
 * 只用「把这块贴到那块板的某一边/某个方向去」来描述，角度与翻转由几何唯一确定，
 * 因此每个造型都是精确共边、互不压叠的合法 7 块装配。
 * 坐标系：u 单位（1u = 96 世界单位），y 轴向下；第一块直接落位。
 */
const L = require('./lib.js');

function up(a, id, ref, dx, dy) {
  for (const m of [0.72, 0.6, 0.45, 0.3, 0.15, 0]) {
    try { return a.attachDir(id, ref, dx, dy, m); } catch (e) { /* 收紧不了就放宽 */ }
  }
  throw new Error('放不下 ' + id);
}

